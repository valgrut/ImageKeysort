def generateRandomImage(x, y, save_path=None):
    """
    Generate a random RGB image of size (x, y).
    """
    # Create random pixel data (values 0–255)
    random_pixels = np.random.randint(0, 256, (y, x, 3), dtype=np.uint8)

    # Convert to image
    img = Image.fromarray(random_pixels, 'RGB')

    # Save if path provided
    if save_path:
        img.save(save_path)

    return img


