class TestSortModeHandler(unittest.TestCase):

    def createTestingData(self, numberOfImages: int):
        # Create a temporary directory
        self.galleryTestSrcDir = QTemporaryDir()

        # Create files inside the temporary directory
        self.files = []
        for i in range(numberOfImages):
            file_path = os.path.join(self.galleryTestSrcDir.path(), f"test_image_{i}.png")
            self.files.append(file_path)
            with open(file_path, 'w') as f:
                f.write(f"Content for test file {i}")  # Add content to the file

    def countFiles(self, dirToCount: QTemporaryDir):
        return len([f for f in os.listdir(dirToCount.path()) if os.path.isfile(os.path.join(dirToCount.path(), f))])

    def setUp(self):
        pass

    def prepare(self, numberOfData=1):
        self.createTestingData(numberOfData)  # self.galleryTestSrcDir
        self.aaDstDir = QTemporaryDir()
        # self.galleryTestSrcDir = ...Generated by method createTestingData(N)

        # Create the application window and button (the GUI to be tested)
        self.window = MainWindow()  # Replace with your actual window class
        self.window.setSortMode()
        self.window.unsetCopyMode()
        self.window.galleryManager.setSourcePath(self.galleryTestSrcDir.path())

        # qInfo(aaDstDir.path(gallerySrcDir.path()))
        self.window.shortcutManager.shortcutTree = {
            "keys": {
                "a": {
                    "dst_path": "",
                    "keys": {
                        "a": {
                            "dst_path": f"{self.aaDstDir.path()}",
                            "keys": {}
                        }
                    }
                }
            }
        }


    def tearDown(self):
        self.window.close()


